"""Email delivery for opt-in My Newsren briefings.

``send_email`` uses SMTP when ``settings.smtp_host`` is configured (STARTTLS
when ``settings.smtp_starttls``, implicit TLS on port 465, login when a user
is set). Without an SMTP host it writes an RFC 822 ``.eml`` file (plain text
plus HTML alternative) to ``settings.outbox_dir`` so local and test runs can
inspect exactly what would have been sent. Credentials are never logged or
included in error messages.

``render_briefing_email`` turns a stored ``Briefing`` (``BriefingOut``
content plus ``CitationRef`` citations) into a subject, an inline-styled HTML
body, and a plain-text body. Every item lists the sources it cites, all text
is HTML-escaped, only http(s) links are rendered as links, and the footer says
the email is an automated personal briefing generated from the cited sources,
with a link to manage preferences or unsubscribe.
"""

from __future__ import annotations

import html
import logging
import secrets
import smtplib
import ssl
import textwrap
from collections.abc import Mapping
from email.message import EmailMessage
from email.policy import SMTP as SMTP_POLICY
from email.utils import formataddr, formatdate, getaddresses, make_msgid, parseaddr
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

from newsren.config import Settings, get_settings
from newsren.models import Briefing, User, utcnow
from newsren.textutil import normalize_space, parse_datetime, slugify, truncate

log = logging.getLogger(__name__)

SMTP_TIMEOUT_SECONDS = 30
MAX_SUBJECT_LENGTH = 150
FOOTER_TEXT = (
    "This is an automated personal briefing generated by The Newsren from the sources cited above. "
    "Each item links to the sources it draws on; please check them before relying on a detail. "
    "Content is informational and educational only and is not investment advice."
)
NO_SOURCE_TEXT = "No source is attached to this item, so treat it as unverified."


class EmailDeliveryError(RuntimeError):
    """SMTP delivery failed (the message never contains credentials)."""


# --------------------------------------------------------------------------
# Sending
# --------------------------------------------------------------------------


def _header_text(value: str) -> str:
    # Collapsing whitespace removes CR/LF, which closes off header injection.
    return normalize_space(value)


def _recipient(to: str) -> str:
    raw = (to or "").strip()
    if not raw or "\r" in raw or "\n" in raw:
        raise ValueError("A single recipient address is required.")
    pairs = getaddresses([raw])
    name, addr = pairs[0] if len(pairs) == 1 else ("", "")
    if addr.count("@") != 1 or any(ch.isspace() for ch in addr) or addr.startswith("@") or addr.endswith("@"):
        raise ValueError(f"Not a valid single recipient address: {raw!r}")
    return formataddr((name, addr)) if name else addr


def _message_domain(settings: Settings) -> str:
    addr = parseaddr(settings.smtp_from)[1]
    return addr.rsplit("@", 1)[-1] if "@" in addr else "newsren.example"


def preferences_url(settings: Settings | None = None) -> str:
    """Where readers manage briefing email preferences or unsubscribe."""
    settings = settings or get_settings()
    return settings.base_url.rstrip("/") + "/me"


def build_message(
    to: str,
    subject: str,
    html_body: str,
    text_body: str,
    settings: Settings | None = None,
    headers: Mapping[str, str] | None = None,
) -> EmailMessage:
    """Build the multipart/alternative message (text first, HTML preferred by capable clients)."""
    settings = settings or get_settings()
    msg = EmailMessage()
    msg["From"] = settings.smtp_from
    msg["To"] = _recipient(to)
    msg["Subject"] = _header_text(subject)[:MAX_SUBJECT_LENGTH] or "The Newsren"
    msg["Date"] = formatdate(usegmt=True)
    msg["Message-ID"] = make_msgid(domain=_message_domain(settings))
    msg["Auto-Submitted"] = "auto-generated"
    msg["List-Unsubscribe"] = f"<{preferences_url(settings)}>"
    for name, value in (headers or {}).items():
        if not name or any(ch in name for ch in ":\r\n ") or not name.isascii():
            raise ValueError(f"Invalid header name {name!r}")
        del msg[name]
        msg[name] = _header_text(value)
    msg.set_content(text_body or "")
    msg.add_alternative(html_body or "", subtype="html")
    return msg


def _write_outbox(msg: EmailMessage, settings: Settings) -> Path:
    outbox = Path(settings.outbox_dir)
    outbox.mkdir(parents=True, exist_ok=True)
    recipient = parseaddr(str(msg["To"]))[1]
    name = f"{utcnow():%Y%m%dT%H%M%S}-{slugify(recipient, 40)}-{secrets.token_hex(4)}.eml"
    path = outbox / name
    path.write_bytes(msg.as_bytes(policy=SMTP_POLICY))
    return path


def _send_smtp(msg: EmailMessage, settings: Settings) -> None:
    host, port = settings.smtp_host, settings.smtp_port
    context = ssl.create_default_context()
    try:
        if port == 465:
            client: smtplib.SMTP = smtplib.SMTP_SSL(host, port, timeout=SMTP_TIMEOUT_SECONDS, context=context)
        else:
            client = smtplib.SMTP(host, port, timeout=SMTP_TIMEOUT_SECONDS)
        with client:
            client.ehlo()
            if settings.smtp_starttls and port != 465:
                client.starttls(context=context)
                client.ehlo()
            if settings.smtp_user:
                client.login(settings.smtp_user, settings.smtp_password)
            client.send_message(msg)
    except (smtplib.SMTPException, OSError) as exc:
        detail = f"{type(exc).__name__}: {exc}"
        if settings.smtp_password:
            detail = detail.replace(settings.smtp_password, "***")
        raise EmailDeliveryError(f"SMTP delivery via {host}:{port} failed ({detail})") from None


def send_email(
    to: str,
    subject: str,
    html: str,
    text: str,
    settings: Settings | None = None,
    *,
    headers: Mapping[str, str] | None = None,
) -> str:
    """Send one email and return its Message-ID (SMTP) or the ``.eml`` path written to the outbox.

    Raises ``ValueError`` for an invalid recipient and ``EmailDeliveryError``
    when the SMTP server cannot be reached or refuses the message.
    """
    settings = settings or get_settings()
    msg = build_message(to, subject, html, text, settings, headers)
    recipient = parseaddr(str(msg["To"]))[1]
    if settings.smtp_host:
        _send_smtp(msg, settings)
        log.info(
            "Sent email %s to %s via %s:%s", msg["Message-ID"], recipient, settings.smtp_host, settings.smtp_port
        )
        return str(msg["Message-ID"])
    path = _write_outbox(msg, settings)
    log.info("SMTP not configured; email to %s written to %s", recipient, path)
    return str(path)


# --------------------------------------------------------------------------
# Rendering a My Newsren briefing
# --------------------------------------------------------------------------

_INK = "#1d2433"
_NAVY = "#142a4a"
_MUTED = "#5b6270"
_RULE = "#e3ded3"


def _e(value: Any) -> str:
    return html.escape(normalize_space(str(value)) if value is not None else "", quote=True)


def _safe_url(url: Any) -> str | None:
    """The URL if it is an absolute http(s) link without whitespace; otherwise None (never linked)."""
    raw = str(url or "").strip()
    if not raw or any(ch.isspace() or ord(ch) < 32 for ch in raw):
        return None
    parts = urlsplit(raw)
    if parts.scheme.lower() not in ("http", "https") or not parts.netloc:
        return None
    return raw


def _date(value: Any) -> str:
    dt = parse_datetime(value) if value else None
    return f"{dt.day} {dt:%b %Y}" if dt else ""


def _as_dict(value: Any) -> dict[str, Any]:
    if hasattr(value, "model_dump"):
        value = value.model_dump()
    return value if isinstance(value, dict) else {}


def _as_list(value: Any) -> list[Any]:
    return list(value) if isinstance(value, list | tuple) else []


class _Sources:
    """Numbers cited sources in order of first use; ignores ids absent from the briefing's citations."""

    def __init__(self, citations: list[Any]):
        self.by_id: dict[str, dict[str, Any]] = {}
        for raw in citations:
            c = _as_dict(raw)
            cid = str(c.get("id") or "").strip()
            if cid and cid not in self.by_id and (c.get("url") or c.get("title")):
                self.by_id[cid] = c
        self.order: list[str] = []

    def number(self, cid: Any) -> int | None:
        key = str(cid or "").strip()
        if key not in self.by_id:
            return None
        if key not in self.order:
            self.order.append(key)
        return self.order.index(key) + 1

    def numbered(self) -> list[tuple[int, dict[str, Any]]]:
        return [(i + 1, self.by_id[cid]) for i, cid in enumerate(self.order)]


def _source_meta(c: dict[str, Any]) -> str:
    bits = [normalize_space(str(c.get("publisher") or ""))]
    published = _date(c.get("published_at"))
    if published:
        bits.append(f"published {published}")
    retrieved = _date(c.get("retrieved_at"))
    if retrieved:
        bits.append(f"retrieved {retrieved}")
    return ", ".join(b for b in bits if b)


def _subject(title: str) -> str:
    title = normalize_space(title) or "Your briefing"
    subject = title if "newsren" in title.lower() else f"{title} | The Newsren"
    return truncate(subject, MAX_SUBJECT_LENGTH)


def _wrap(text: str, indent: str = "", hanging: str | None = None) -> str:
    return textwrap.fill(
        normalize_space(text),
        width=78,
        initial_indent=indent,
        subsequent_indent=indent if hanging is None else hanging,
        break_long_words=False,
        break_on_hyphens=False,
    )


def render_briefing_email(
    briefing: Briefing, user: User, settings: Settings | None = None
) -> tuple[str, str, str]:
    """Render a personal briefing as ``(subject, html, text)``.

    Uses ``briefing.content`` (``BriefingOut`` shape) and resolves each item's
    ``citation_ids`` against ``briefing.citations``; ids without a matching
    citation are dropped rather than shown as unsourced links.
    """
    settings = settings or get_settings()
    base = settings.base_url.rstrip("/")
    prefs = preferences_url(settings)
    content = _as_dict(briefing.content)
    title = normalize_space(content.get("title") or briefing.title or "Your Newsren briefing")
    intro = normalize_space(content.get("intro"))
    closing = normalize_space(content.get("closing_note"))
    name = normalize_space(user.display_name) or "there"
    sources = _Sources(_as_list(briefing.citations))

    h: list[str] = [
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>{_e(title)}</title></head>",
        f'<body style="margin:0;padding:0;background:#f6f3ec;color:{_INK};">',
        '<div style="max-width:640px;margin:0 auto;padding:24px;background:#ffffff;'
        "font-family:Georgia,'Times New Roman',serif;font-size:16px;line-height:1.5;\">",
        f'<p style="margin:0 0 4px;font:600 12px/1.4 Arial,sans-serif;letter-spacing:.08em;'
        f'text-transform:uppercase;color:{_NAVY};">The Newsren &middot; My Newsren briefing</p>',
        f'<h1 style="margin:0 0 16px;font-size:24px;line-height:1.25;color:{_NAVY};">{_e(title)}</h1>',
        f'<p style="margin:0 0 12px;">Hi {_e(name)},</p>',
    ]
    t: list[str] = ["THE NEWSREN - MY NEWSREN BRIEFING", title, "=" * min(len(title), 78), "", f"Hi {name},", ""]
    if intro:
        h.append(f'<p style="margin:0 0 16px;">{_e(intro)}</p>')
        t += [_wrap(intro), ""]

    for section in _as_list(content.get("sections")):
        section = _as_dict(section)
        items = [_as_dict(i) for i in _as_list(section.get("items"))]
        heading = normalize_space(section.get("heading"))
        if not items and not heading:
            continue
        if heading:
            h.append(
                f'<h2 style="margin:28px 0 10px;padding-top:16px;border-top:1px solid {_RULE};'
                f'font-size:19px;color:{_NAVY};">{_e(heading)}</h2>'
            )
            t += [heading.upper(), "-" * min(len(heading), 78), ""]
        for item in items:
            _render_item(item, sources, base, h, t)

    if closing:
        h.append(f'<p style="margin:24px 0 0;">{_e(closing)}</p>')
        t += [_wrap(closing), ""]

    numbered = sources.numbered()
    if numbered:
        h.append(
            f'<h2 style="margin:28px 0 8px;padding-top:16px;border-top:1px solid {_RULE};'
            f'font-size:16px;color:{_NAVY};">Sources</h2>'
            f'<ol style="margin:0;padding-left:22px;font-size:14px;color:{_INK};">'
        )
        t += ["SOURCES", ""]
        for n, c in numbered:
            label = normalize_space(c.get("title") or c.get("url") or f"Source {n}")
            url = _safe_url(c.get("url"))
            meta = _source_meta(c)
            link = (
                f'<a href="{html.escape(url, quote=True)}" style="color:{_NAVY};">{_e(label)}</a>'
                if url
                else f"{_e(label)} (link unavailable)"
            )
            h.append(f'<li style="margin:0 0 6px;">{link}{" &mdash; " + _e(meta) if meta else ""}</li>')
            t.append(_wrap(f"[{n}] {label}" + (f" - {meta}" if meta else ""), "", "    "))
            t.append(f"    {url}" if url else "    (link unavailable)")
        h.append("</ol>")
        t.append("")

    h += [
        f'<div style="margin:32px 0 0;padding-top:12px;border-top:1px solid {_RULE};'
        f'font:12px/1.5 Arial,sans-serif;color:{_MUTED};">',
        f'<p style="margin:0 0 8px;">{_e(FOOTER_TEXT)}</p>',
        '<p style="margin:0;">You receive this because you turned on email briefings in My Newsren. '
        f'<a href="{html.escape(prefs, quote=True)}" style="color:{_NAVY};">'
        "Manage preferences or unsubscribe</a>.</p>",
        "</div></div></body></html>",
    ]
    t += [
        "--",
        _wrap(FOOTER_TEXT),
        "",
        "You receive this because you turned on email briefings in My Newsren.",
        f"Manage preferences or unsubscribe: {prefs}",
        "",
    ]
    return _subject(title), "\n".join(h), "\n".join(t)


def _render_item(item: dict[str, Any], sources: _Sources, base: str, h: list[str], t: list[str]) -> None:
    headline = normalize_space(item.get("headline")) or "Update"
    changed = normalize_space(item.get("what_changed"))
    matters = normalize_space(item.get("why_it_matters"))
    interest = normalize_space(item.get("interest"))
    numbers = [n for n in (sources.number(cid) for cid in _as_list(item.get("citation_ids"))) if n is not None]
    numbers = list(dict.fromkeys(numbers))
    brief_id = item.get("brief_id")
    brief_url = f"{base}/briefs/{int(brief_id)}" if isinstance(brief_id, int) and brief_id > 0 else None

    h.append('<div style="margin:0 0 20px;">')
    h.append(f'<h3 style="margin:0 0 6px;font-size:17px;line-height:1.3;color:{_INK};">{_e(headline)}</h3>')
    t.append(_wrap(headline, "* ", "  "))
    if interest:
        h.append(
            f'<p style="margin:0 0 6px;font:12px/1.4 Arial,sans-serif;color:{_MUTED};">'
            f"Matches your interest: {_e(interest)}</p>"
        )
        t.append(_wrap(f"Matches your interest: {interest}", "  "))
    if changed:
        h.append(f'<p style="margin:0 0 6px;"><strong>What changed:</strong> {_e(changed)}</p>')
        t.append(_wrap(f"What changed: {changed}", "  "))
    if matters:
        h.append(f'<p style="margin:0 0 6px;"><strong>Why it matters:</strong> {_e(matters)}</p>')
        t.append(_wrap(f"Why it matters: {matters}", "  "))

    links: list[str] = []
    for n in numbers:
        c = sources.by_id[sources.order[n - 1]]
        url = _safe_url(c.get("url"))
        label = f"[{n}] {normalize_space(c.get('title') or '')}".strip()
        publisher = normalize_space(c.get("publisher"))
        text_label = _e(label) + (f" ({_e(publisher)})" if publisher else "")
        links.append(
            f'<a href="{html.escape(url, quote=True)}" style="color:{_NAVY};">{text_label}</a>'
            if url
            else text_label
        )
    if links:
        h.append(
            f'<p style="margin:0;font:13px/1.5 Arial,sans-serif;color:{_MUTED};">Sources: '
            + " &middot; ".join(links)
            + "</p>"
        )
        t.append("  Sources: " + " ".join(f"[{n}]" for n in numbers))
    else:
        h.append(f'<p style="margin:0;font:13px/1.5 Arial,sans-serif;color:{_MUTED};">{_e(NO_SOURCE_TEXT)}</p>')
        t.append(f"  {NO_SOURCE_TEXT}")
    if brief_url:
        h.append(
            f'<p style="margin:4px 0 0;font:13px/1.5 Arial,sans-serif;">'
            f'<a href="{html.escape(brief_url, quote=True)}" style="color:{_NAVY};">Read the full brief</a></p>'
        )
        t.append(f"  Full brief: {brief_url}")
    h.append("</div>")
    t.append("")
